//! One-time client bundle construction. No private material is read outside this context.

use super::PkiError;

pub struct DownloadBundle {
    pub filename: String,
    pub bytes: Vec<u8>,
}

pub fn build_download_bundle(
    name: &str,
    server_name: &str,
    ca_cert_pem: &[u8],
    client_cert_pem: &[u8],
    client_key: &[u8],
) -> Result<DownloadBundle, PkiError> {
    let mut tar = tar::Builder::new(Vec::new());
    append_tar(&mut tar, "ca.crt", ca_cert_pem)?;
    append_tar(&mut tar, "client.crt", client_cert_pem)?;
    append_tar(&mut tar, "client.key", client_key)?;
    let config = format!(
        "# Generated by home-llm-gateway for pair {name}\n# Put these files beside this config.\ncloud_addr: \"<gateway-host>:4433\"\nca: ca.crt\ncert: client.crt\nkey: client.key\nserver_name: {server_name}\n"
    );
    append_tar(&mut tar, "client-config.example.yml", config.as_bytes())?;
    let bytes = tar.into_inner().map_err(PkiError::Io)?;
    Ok(DownloadBundle {
        filename: format!("hlmg-client-{name}.tar"),
        bytes,
    })
}

fn append_tar(tar: &mut tar::Builder<Vec<u8>>, name: &str, bytes: &[u8]) -> Result<(), PkiError> {
    let mut header = tar::Header::new_gnu();
    header.set_size(bytes.len() as u64);
    header.set_mode(0o600);
    header.set_cksum();
    tar.append_data(&mut header, name, bytes)
        .map_err(PkiError::Io)
}
